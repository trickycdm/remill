/**
 * icon.tsx — inline SVG icons for the admin (Hono JSX, server-rendered).
 *
 * No icon font, no CDN, no lucide-react runtime — every icon is a 24×24 stroke
 * SVG whose path data is copied verbatim from Lucide (lucide.dev, ISC). This is
 * the sanctioned iconography approach (DESIGN_SYSTEM.md): add an icon by pasting
 * its Lucide paths into a new exported function here.
 *
 * Decorative by default (`aria-hidden="true"`) — icons carry no meaning a screen
 * reader needs when they sit beside a text label. For an icon-only control, put
 * the label on the BUTTON via `aria-label`, not on the icon (A11Y_STANDARDS.md).
 *
 * Usage:
 *   <Menu class="size-5" />
 *   <Spinner class="size-4 rm-anim-spin" />
 */

import type { FC } from 'hono/jsx';

export interface IconProps {
  readonly class?: string;
  readonly size?: number | string;
  readonly 'aria-hidden'?: 'true' | 'false';
  readonly 'aria-label'?: string;
}

/** The type of every icon component here — usable as a JSX element. */
export type IconComponent = FC<IconProps>;

/** Shared 24×24 stroke wrapper for all icons. */
function Svg({
  children,
  class: cls,
  size = 24,
  'aria-hidden': ariaHidden = 'true',
  'aria-label': ariaLabel,
}: IconProps & { children: unknown }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      class={cls}
      aria-hidden={ariaHidden}
      aria-label={ariaLabel}
      role={ariaLabel ? 'img' : undefined}
    >
      {children}
    </svg>
  );
}

